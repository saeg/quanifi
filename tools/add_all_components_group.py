CATEGORY_ORDER = [
    "Circuit builders",
    "Hamiltonians & problem encoders",
    "Algorithms (all-in-one solvers)",
    "PennyLane QML lane",
    "Simulators",
    "Hardware execution",
    "Hardware batch lane",
    "Differential & mutation-testing infrastructure",
    "Reporting & utility",
    "Other",
]


def build_group(group_id, processors):
    """One labelled block per category, columns of ROWS_PER_COL, left to right."""
    by_category = {}
    for p in processors:
        by_category.setdefault(p["category"], []).append(p)

    ordered = [c for c in CATEGORY_ORDER if c in by_category]
    ordered += sorted(c for c in by_category if c not in CATEGORY_ORDER)

    nodes, labels = [], []
    x = 0.0
    for category in ordered:
        members = sorted(by_category[category], key=lambda p: p["name"])
        columns = (len(members) + ROWS_PER_COL - 1) // ROWS_PER_COL

        labels.append(make_label(
            "%s  (%d)" % (category, len(members)),
            x, 0.0, (columns - 1) * COL_W + PROCESSOR_SIZE[0], LABEL_H, group_id))

        for index, proc in enumerate(members):
            col, row = divmod(index, ROWS_PER_COL)
            nodes.append(make_processor(
                name=proc["name"],
                proc_type=proc["name"],
                bundle={"group": "org.apache.nifi",
                        "artifact": "python-extensions",
                        "version": proc["version"]},
                properties=proc["properties"],
                x=x + col * COL_W,
                y=snap_up(LABEL_H + MIN_GAP_Y) + row * ROW_H,
                group_id=group_id,
                scheduled_state=NOT_RUNNING,
                auto_terminate=proc["relationships"],
            ))
        x += columns * COL_W + BLOCK_GAP
    return nodes, labels


# --------------------------------------------------------------------------

def group_name(category):
    if not category:
        return GROUP_NAME
    slug = re.sub(r"[^A-Za-z0-9]+", "", category.title())
    return "%s-%s" % (GROUP_NAME, slug)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--flow", help="path to flow.json.gz (NiFi must be stopped)")
    ap.add_argument("--category",
                    help="add only this category, as its own group. Adding all 83 "
                         "processors at once can wedge the Python bridge on "
                         "startup; one block at a time is the reliable path.")
    ap.add_argument("--list-categories", action="store_true",
                    help="print the category names --category accepts")
    ap.add_argument("--remove", action="store_true", help="delete the group instead")
    ap.add_argument("--dry-run", action="store_true",
                    help="discover and report, touch no files")
    args = ap.parse_args()

    processors = categorise(discover())
    if args.category:
        known = {p["category"] for p in processors}
        if args.category not in known:
            raise SystemExit("unknown category %r; known: %s"
                             % (args.category, sorted(known)))
        processors = [p for p in processors if p["category"] == args.category]
    print("discovered %d processors" % len(processors))
    counts = {}
    for p in processors:
        counts[p["category"]] = counts.get(p["category"], 0) + 1
    for category in sorted(counts, key=lambda c: (-counts[c], c)):
        print("  %-48s %d" % (category, counts[category]))

    versions = {}
    for p in processors:
        versions.setdefault(p["version"], []).append(p["name"])
    print("bundle versions: %s" % {v: len(n) for v, n in sorted(versions.items())})

    incomplete = [p for p in processors if p["missing_required"]]
    if incomplete:
        print("\n%d processors have required properties with no default; they will "
              "show as invalid until configured:" % len(incomplete))
        for p in sorted(incomplete, key=lambda p: p["name"]):
            print("  %-34s %s" % (p["name"], ", ".join(p["missing_required"])))

    if args.list_categories:
        return
    if args.dry_run:
        return
    if not args.flow:
        raise SystemExit("--flow is required unless --dry-run")

    flow_path = Path(args.flow).expanduser()
    if not flow_path.exists():
        raise SystemExit("no such flow file: %s" % flow_path)

    backup = flow_path.with_name(
        "%s.bak_allcomponents_%s"
        % (flow_path.name, datetime.now().strftime("%Y%m%d_%H%M%S_%f")))
    shutil.copy2(flow_path, backup)
    with gzip.open(flow_path, "rt", encoding="utf-8") as handle:
        flow = json.load(handle)

    root = flow["rootGroup"]
    groups = root.setdefault("processGroups", [])
    name = group_name(args.category)
    existing = [g for g in groups if g.get("name") == name]

    if args.remove:
        if not existing:
            raise SystemExit("group not present: %s" % name)
        groups[:] = [g for g in groups if g.get("name") != name]
        action = "removed"
    else:
        if existing:
            raise SystemExit("group already exists: %s (use --remove first)" % name)
        group_id = uid()
        nodes, labels = build_group(group_id, processors)
        bad = sorted({n["scheduledState"] for n in nodes} - VALID_SCHEDULED_STATES)
        if bad:
            raise SystemExit("refusing to write: invalid scheduledState %s" % bad)
        groups.append({
            "identifier": group_id,
            "instanceIdentifier": uid(),
            "name": name,
            "comments": GROUP_COMMENT,
            "position": {"x": GROUP_X, "y": GROUP_Y},
            "processGroups": [], "remoteProcessGroups": [],
            "processors": nodes, "connections": [],
            "inputPorts": [], "outputPorts": [], "labels": labels, "funnels": [],
            "controllerServices": [],
            "defaultFlowFileExpiration": "0 sec",
            "defaultBackPressureObjectThreshold": 10000,
            "defaultBackPressureDataSizeThreshold": "1 GB",
            "scheduledState": "ENABLED",
            "executionEngine": "INHERITED",
            "maxConcurrentTasks": 1,
            "statelessFlowTimeout": "1 min",
            "flowFileOutboundPolicy": "STREAM_WHEN_AVAILABLE",
            "flowFileConcurrency": "UNBOUNDED",
            "componentType": "PROCESS_GROUP",
            "groupIdentifier": root["identifier"],
        })
        action = "added %d processors, %d labels, 0 connections" % (len(nodes), len(labels))

    with gzip.open(flow_path, "wt", encoding="utf-8") as handle:
        json.dump(flow, handle)

    if not args.remove:
        print("\nNOTE: NiFi launches one Python process per processor instance. "
              "Check that\n      nifi.python.max.processes in conf/nifi.properties "
              "exceeds the total\n      number of Python processors in the flow, or "
              "NiFi will hang on startup\n      with no error (see this file's "
              "docstring).")

    print("\n%s: %s" % (name, action))
    print("flow  : %s" % flow_path)
    print("backup: %s" % backup)
    if not args.remove:
        print("\nStart NiFi and open %s at (%d, %d). Everything is stopped; "
              "nothing will run." % (name, GROUP_X, GROUP_Y))


if __name__ == "__main__":
    main()
