#!/usr/bin/env python3
"""Add an AllComponents process group holding every Quanifi processor.

Built for documentation screenshots: one instance of each processor class in
nifi_extensions/, laid out in labelled blocks by category, with no connections
between them.

Nothing here is guesswork. The tool imports each processor class through the
same nifiapi stubs the unit tests use and reads three things off it:

  * ProcessorDetails.version  -> the bundle version. These are NOT all the same
    (most are 0.1.0, a few 0.2.0, one 0.1.1), and a wrong version makes NiFi
    fail to resolve the type, which shows up as a ghost component rather than
    an error.
  * getRelationships()        -> every relationship is auto-terminated, so 80-odd
    unconnected processors do not each carry a validation warning in the
    screenshot. Processors that do not override it get the framework defaults
    (success, failure, original), which is what the live flow uses.
  * getPropertyDescriptors()  -> declared defaults are written into the
    processor's properties, so the components render configured rather than
    empty. Required properties with no default are left unset and reported at
    the end; those are the only ones that will still show as invalid.

Categories come from docs/COMPONENTS.md, so the screenshot matches the document
it illustrates. Processors not listed there (the 2026-08 hardware batch lane)
are classified by name and grouped under "Hardware batch lane".

NiFi must be stopped. A timestamped backup of the flow is written first.

BEFORE YOU RUN THIS, raise the Python process limits in conf/nifi.properties:

    nifi.python.max.processes=400                     # default 100
    nifi.python.max.processes.per.extension.type=20   # default 10

NiFi launches a Python process per processor instance. This group adds 83 of
them to a flow that already held 121, and at the default limit of 100 the
bridge exhausts its pool mid-startup: the main thread parks forever in
StandardPythonBridge.createProcessor -> getProcessorTypes, waiting on a py4j
lock held by a connection that is itself waiting on a Python process that can
never be launched. NiFi does not log an error, does not time out, and never
finishes starting -- the only symptom is that the log stops mid-initialisation
and the UI never answers. With the limits raised, the same flow starts in about
a minute.

Expect the first start after adding this group to be slow and to consume disk:
NiFi builds a separate virtualenv per processor type under work/python, and the
types that were not previously on the canvas each pull their own dependencies.

Even with the limits raised, adding all 83 at once is not reliable. Measured on
2026-08-19 against a flow already holding 121 Python processors: one start
succeeded in about 15 seconds, and two others wedged at the same place -- the
bridge initialises BraketSimulator, the Python side reports the process started
and pinged, and nothing happens afterwards. Same processor both times, so it is
ordering-dependent rather than random.

Hence --category. Adding one block at a time keeps the instance count near what
the flow already carries, which is the configuration known to start. For a full
set of screenshots, add a block, start NiFi, photograph it, remove it, and move
to the next.

Usage:
  python tools/add_all_components_group.py --flow ~/projects/nifi-2.9.0/conf/flow.json.gz
  python tools/add_all_components_group.py --flow ... --category "Simulators"
  python tools/add_all_components_group.py --flow ... --remove
  python tools/add_all_components_group.py --dry-run --list-categories
"""
import argparse
import gzip
import importlib
import inspect
import json
import re
import shutil
import sys
import uuid
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "experiments"))

from add_flow import make_processor, make_label  # noqa: E402
from canvas_spacing import (  # noqa: E402
    MIN_GAP_Y, PITCH, PROCESSOR_SIZE, snap_up,
)

GROUP_NAME = "AllComponents"
GROUP_COMMENT = (
    "Every Quanifi processor, one instance each, no connections. Exists for "
    "documentation screenshots: blocks and labels follow the categories in "
    "docs/COMPONENTS.md. Generated by tools/add_all_components_group.py; edit "
    "the tool rather than the canvas, and re-run it after adding a processor."
)

# Clear of every existing group (the lowest is OfficialExperiment-HW at y=-3848).
GROUP_X, GROUP_Y = -25000.0, -4400.0

VALID_SCHEDULED_STATES = {"ENABLED", "DISABLED", "RUNNING"}
NOT_RUNNING = "ENABLED"

# Framework defaults when a processor does not override getRelationships().
# Confirmed against the running flow, where 34 python processors auto-terminate
# "original" alongside success/failure.
DEFAULT_RELATIONSHIPS = ("success", "failure", "original")

COL_W, ROW_H = PITCH
BLOCK_GAP = 344.0
ROWS_PER_COL = 10
LABEL_H = 44.0


def uid():
    return str(uuid.uuid4())


# --------------------------------------------------------------------------
# discovery
# --------------------------------------------------------------------------

def install_stubs():
    """nifiapi stubs, plus a PropertyDescriptor that remembers `required`.

    The stub in tests/conftest.py keeps only name and default_value. The patch
    has to land before any processor module is imported, because they bind the
    class at import time.
    """
    import _harness  # noqa: F401  (side effect: stubs + extensions on sys.path)
    props = sys.modules["nifiapi.properties"]
    base = props.PropertyDescriptor

    class PropertyDescriptor(base):
        def __init__(self, name, description="", required=False,
                     default_value=None, **kwargs):
            super().__init__(name, description, required, default_value, **kwargs)
            self.required = bool(required)

    props.PropertyDescriptor = PropertyDescriptor


def discover():
    """Every processor class in nifi_extensions, with what the canvas needs."""
    install_stubs()
    found = []
    for path in sorted((ROOT / "nifi_extensions").glob("*.py")):
        if path.stem.startswith("_"):
            continue
        module = importlib.import_module(path.stem)
        for name, obj in vars(module).items():
            if not inspect.isclass(obj) or obj.__module__ != module.__name__:
                continue
            details = getattr(obj, "ProcessorDetails", None)
            if details is None or not hasattr(details, "version"):
                continue

            relationships, properties, missing = list(DEFAULT_RELATIONSHIPS), {}, []
            try:
                instance = obj()
            except Exception:
                instance = None

            if instance is not None and hasattr(instance, "getRelationships"):
                try:
                    declared = [r.name for r in instance.getRelationships()]
                    if declared:
                        # NiFi adds `failure` to a Python processor's own set: four
                        # processors here declare pass/fail or control_dissent and
                        # still carry a framework `failure` that has to be
                        # auto-terminated or the component is invalid.
                        if "failure" not in declared:
                            declared.append("failure")
                        relationships = declared
                except Exception:
                    pass

            if instance is not None and hasattr(instance, "getPropertyDescriptors"):
                try:
                    for d in instance.getPropertyDescriptors():
                        default = getattr(d, "default_value", None)
                        # An empty-string default is a "leave me unset" marker, not a
                        # value: writing it back fails validation on typed properties
                        # (Random Seed on the VQE and QAOA processors validates as an
                        # integer and rejects "").
                        if default is not None and str(default) != "":
                            properties[d.name] = str(default)
                        elif getattr(d, "required", False):
                            missing.append(d.name)
                except Exception:
                    pass

            found.append({
                "name": name,
                "version": details.version,
                "relationships": relationships,
                "properties": properties,
                "missing_required": missing,
                "deprecated": "deprecated" in (getattr(details, "description", "") or "").lower(),
            })
    return found


def categorise(processors):
    """Category per processor, from docs/COMPONENTS.md headings where possible."""
    doc = (ROOT / "docs" / "COMPONENTS.md")
    documented, category = {}, None
    if doc.exists():
        for line in doc.read_text(encoding="utf-8").splitlines():
            if line.startswith("## "):
                heading = line[3:].strip()
                category = None if heading == "Summary" else heading
            elif line.startswith("### ") and category:
                pass  # sub-headings stay inside their ## category
            elif line.startswith("| `") and category:
                m = re.match(r"\|\s*`([A-Za-z0-9_]+)`", line)
                if m:
                    documented[m.group(1)] = category

    def fallback(name):
        if re.search(r"Batch(Submitter|Poller|ResultExpander)|IQMJob|IBMBatch", name):
            return "Hardware batch lane"
        if re.search(r"Oracle|Assertion|Mutator|MutationScore|Comparison|TestCase", name):
            return "Differential & mutation-testing infrastructure"
        if re.search(r"Report|Unitary|Quanifi", name):
            return "Reporting & utility"
        if re.search(r"Simulator|Sampler|Device", name):
            return "Simulators"
        return "Other"

    for p in processors:
        p["category"] = documented.get(p["name"]) or fallback(p["name"])
    return processors


